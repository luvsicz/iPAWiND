def get(string_id: str, user_id: int) -> str:
    cursor.execute(f"SELECT lang FROM UsersLangs WHERE id={user_id}")
    try:
        lang = cursor.fetchone()[0]
        return strings[lang][string_id]
    except TypeError:
        return strings["en"][string_id]
